import assert from 'node:assert/strict';
import { test } from 'node:test';
import { spawnSync } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

test('headless bootstrap creates one administrator, fails closed on missing credentials and preserves edits on restart', { timeout: 90000 }, () => {
  const directory = path.resolve('.test-data', `bootstrap-${Date.now()}`);
  mkdirSync(directory, { recursive: true });
  const file = path.join(directory, 'synthetic.sqlite');
  const env = { ...process.env, DATABASE_URI: `file:${file.replaceAll('\\', '/')}`, DATABASE_URL: 'postgresql://do-not-connect.invalid/production', DATABASE_URL_UNPOOLED: 'postgresql://do-not-connect.invalid/production', PAYLOAD_SECRET: 'synthetic-bootstrap-secret-with-32-characters', WEB_URL: 'http://127.0.0.1:8080', DISABLE_PAYLOAD_HMR: 'true' };
  for (const key of ['RENDER', 'LTSP_TEST_MODE', 'INITIAL_ADMIN_EMAIL', 'INITIAL_ADMIN_PASSWORD', 'INITIAL_ADMIN_NAME']) delete env[key];
  const run = (script, extra = {}) => spawnSync(process.execPath, ['--import', 'tsx', `scripts/${script}.ts`], { env: { ...env, ...extra }, encoding: 'utf8', timeout: 30000 });
  const succeeds = result => assert.equal(result.status, 0, result.stderr || result.stdout);
  succeeds(run('seed'));
  let database = new DatabaseSync(file);
  assert.equal(database.prepare('SELECT count(*) AS total FROM users').get().total, 0);
  database.close();
  const missing = run('create-admin');
  assert.notEqual(missing.status, 0);
  assert.match(missing.stderr, /Set INITIAL_ADMIN_EMAIL and INITIAL_ADMIN_PASSWORD/);
  const short = run('create-admin', { INITIAL_ADMIN_EMAIL: 'admin@example.test', INITIAL_ADMIN_PASSWORD: 'short' });
  assert.notEqual(short.status, 0);
  const password = 'Synthetic-bootstrap-password-2026';
  const created = run('create-admin', { INITIAL_ADMIN_EMAIL: 'admin@example.test', INITIAL_ADMIN_PASSWORD: password });
  succeeds(created);
  assert.ok(!(created.stdout + created.stderr).includes(password));
  database = new DatabaseSync(file);
  const original = database.prepare('SELECT role, hash FROM users').get();
  assert.equal(original.role, 'admin');
  database.prepare('UPDATE services SET title = ? WHERE slug = ?').run('Synthetic edited service', 'home-follow-up');
  database.close();
  succeeds(run('seed'));
  succeeds(run('create-admin', { INITIAL_ADMIN_EMAIL: 'different@example.test', INITIAL_ADMIN_PASSWORD: 'Different-synthetic-password-2026' }));
  database = new DatabaseSync(file);
  assert.equal(database.prepare('SELECT count(*) AS total FROM users').get().total, 1);
  assert.equal(database.prepare('SELECT hash FROM users').get().hash, original.hash);
  assert.equal(database.prepare('SELECT title FROM services WHERE slug = ?').get('home-follow-up').title, 'Synthetic edited service');
  database.close();
  const blocked = run('seed', { RENDER: 'true', LTSP_TEST_MODE: 'true', DATABASE_URI: 'postgresql://synthetic@127.0.0.1:5547/blocked_test' });
  assert.notEqual(blocked.status, 0);
  assert.match(blocked.stderr, /Synthetic test credentials must not be seeded on Render/);
});
